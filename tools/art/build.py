"""Render every exercise animation.

    python3 -I tools/art/build.py [id ...]

Writes AzerothFit/Media/Ex/<id>.tga (512x128, 4 frames) and a large preview
tools/art/preview/<id>.png to check by eye. Pose files: tools/art/poses_*.py.
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import figure  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "AzerothFit", "Media", "Ex")
PREVIEW = os.path.join(HERE, "preview")


def load_all():
    exercises = {}
    for name in sorted(os.listdir(HERE)):
        if name.startswith("poses_") and name.endswith(".py") and name != "poses_example.py":
            spec = importlib.util.spec_from_file_location(name[:-3], os.path.join(HERE, name))
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            for k, v in mod.EXERCISES.items():
                if k in exercises:
                    raise SystemExit("duplicate exercise id: " + k)
                exercises[k] = v
    return exercises


def main(ids):
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(PREVIEW, exist_ok=True)
    exercises = load_all()
    if not exercises:  # only the example file exists yet
        spec = importlib.util.spec_from_file_location("poses_example", os.path.join(HERE, "poses_example.py"))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        exercises = mod.EXERCISES
    total = 0
    for k, (frames, props) in sorted(exercises.items()):
        if ids and k not in ids:
            continue
        img = figure.render(frames, props)
        path = os.path.join(OUT, k + ".tga")
        figure.save_tga(img, path)
        figure.preview(img, os.path.join(PREVIEW, k + ".png"))
        size = os.path.getsize(path)
        total += size
        print(f"{k:24s} {size / 1024:6.1f} KB")
    print(f"total {total / 1024:.1f} KB")
    if not ids:
        # Tell the addon which exercises have a picture.
        lines = ["-- Generated by tools/art/build.py: exercises that have an animation in Media\\Ex.",
                 "local _, AF = ...", "AF.Art = {"]
        lines += [f'\t{k} = true,' for k in sorted(exercises)]
        lines.append("}")
        with open(os.path.join(ROOT, "AzerothFit", "Data", "Art.lua"), "w") as fh:
            fh.write("\n".join(lines) + "\n")
        print("wrote Data/Art.lua with", len(exercises), "exercises")


if __name__ == "__main__":
    main(set(sys.argv[1:]))
